"""Render/check exactly three parity outputs. Does not inspect Git or contact services."""
from __future__ import annotations

import argparse
import os
from pathlib import Path
import stat
import sys
import tempfile

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).absolute().parents[2]))

from tools.parity.markdown import render_markdown
from tools.parity.model import MAX_INPUT_BYTES, StatusError, parse, validate_commit
from tools.parity.render import render_images

OUTPUT_NAMES = ("progress.gif", "progress.png", "PROGRESS.md")


def ordinary(path: Path, *, directory: bool = False, required: bool = True) -> None:
    """Check lexical absolute path before resolving anything; resolving could hide links."""
    for index, current in enumerate((path, *path.parents)):
        try:
            info = current.lstat()
        except FileNotFoundError:
            if index == 0 and required:
                raise StatusError("required tracker input/output path is missing") from None
            continue
        if stat.S_ISLNK(info.st_mode) or getattr(info, "st_file_attributes", 0) & 0x400:
            raise StatusError("tracker paths cannot traverse a symlink or reparse point")
        is_directory = directory if index == 0 else True
        if not (stat.S_ISDIR(info.st_mode) if is_directory else stat.S_ISREG(info.st_mode)):
            raise StatusError("tracker paths require ordinary files and directory ancestors")


def _read(path: Path, maximum: int) -> bytes:
    ordinary(path)
    descriptor = os.open(path, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0))
    with os.fdopen(descriptor, "rb") as stream:
        info = os.fstat(stream.fileno())
        if not stat.S_ISREG(info.st_mode) or info.st_size > maximum:
            raise StatusError("tracker file is not ordinary or exceeds its byte bound")
        result = stream.read(maximum + 1)
        if len(result) > maximum:
            raise StatusError("tracker file exceeded its byte bound while reading")
        return result


def _write(path: Path, data: bytes) -> None:
    ordinary(path, required=False)
    ordinary(path.parent, directory=True)
    descriptor, temporary = tempfile.mkstemp(prefix=".parity-", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        ordinary(path, required=False)
        ordinary(path.parent, directory=True)
        os.replace(temporary, path)
    finally:
        # Only the fresh temporary file created by this call is ever removed.
        if os.path.lexists(temporary):
            os.unlink(temporary)


def generate(root: Path, commit: str, *, check: bool = False) -> bool:
    root = Path(os.path.abspath(root))
    ordinary(root, directory=True)
    ordinary(root / "WolfConquer.sln")
    folder = root / "docs" / "parity"
    status = parse(_read(folder / "status.json", MAX_INPUT_BYTES))
    commit = validate_commit(commit)
    targets = tuple(folder / name for name in OUTPUT_NAMES)
    for target in targets:
        ordinary(target, required=check)
    gif, png = render_images(status, commit)
    outputs = (gif, png, render_markdown(status, commit))
    if check:
        return all(_read(path, 2 * 1024 * 1024) == content for path, content in zip(targets, outputs))
    for path, content in zip(targets, outputs):
        _write(path, content)
    return True


def main(arguments: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--commit", required=True, help="forty hexadecimal characters; supplied by the caller")
    parser.add_argument("--check", action="store_true", help="compare generated bytes without writing")
    args = parser.parse_args(arguments)
    try:
        if not generate(args.root, args.commit, check=args.check):
            print("Parity outputs differ from the deterministic snapshot.", file=sys.stderr)
            return 1
    except (StatusError, OSError) as error:
        print(f"Parity tracker refused: {error}", file=sys.stderr)
        return 2
    print("Parity outputs match." if args.check else "Generated progress.gif, progress.png, and PROGRESS.md.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
